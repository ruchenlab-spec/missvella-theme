// Regenerate code-only catalog snippets from the reviewed source record.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'data/material-guide-catalog.json'), 'utf8'));
const quote = value => {
  if (/["\r\n\\]/.test(value)) throw new Error('Liquid literal requires review: ' + value);
  return '"' + value + '"';
};
const slug = value => value.toLowerCase().replace(/[^a-z0-9]+/g, '-');
for (const kind of ['color', 'fabric']) {
  const items = kind === 'fabric' ? data.fabricDisplayOrder.map(name => {
    const entry = data.fabrics.find(entry => entry.name === name);
    if (!entry) throw new Error('Unknown displayed fabric: ' + name);
    return entry;
  }) : data.colors;
  const names = new Set();
  const lines = ['{% comment %}Generated by scripts/build-material-guide-catalog.cjs. Source: data/material-guide-catalog.json.{% endcomment %}'];
  for (const entry of items) {
    if (names.has(entry.name)) throw new Error('Duplicate catalog name: ' + entry.name);
    names.add(entry.name);
    const values = {entry_id: slug(entry.name), name: entry.name, description: entry.description, image_file: entry.image?.file || '', image_caption: entry.imageCaption, product_handle: entry.product};
    if (kind === 'color') Object.assign(values, {family: entry.family, hex: entry.hex});
    else Object.assign(values, {finish: entry.finish, drape: entry.drape, feel: entry.feel, notes: entry.notes, detail_position: entry.detailPosition, display_number: String(names.size).padStart(2, '0')});
    for (const [key, value] of Object.entries(values)) {
      if (typeof value !== 'string') throw new Error('Missing field: ' + entry.name + '/' + key);
    }
    const params = Object.entries(values).map(([key, value]) => key + ': ' + quote(value)).join(', ');
    lines.push(`{% render 'guide-${kind}-entry', section: section${kind === 'color' ? ', mode: mode' : ''}, ${params} %}`);
  }
  fs.writeFileSync(path.join(root, `theme/snippets/guide-${kind}-catalog.liquid`), lines.join('\n') + '\n');
  console.log(`Generated ${items.length} ${kind} entries`);
}

// The picker and filters share broader families than the editorial guide.
const families = [
  {label: 'Blues', key: 'blues', chip: 'Sky Blue', families: ['Blue']},
  {label: 'Greens', key: 'greens', chip: 'Peacock', families: ['Green']},
  {label: 'Purples', key: 'purples', chip: 'Purple', families: ['Purple']},
  {label: 'Pinks & Reds', key: 'pinks', chip: 'Dusty Rose', families: ['Pink', 'Red', 'Rose Gold']},
  {label: 'Yellow', key: 'yellow', chip: 'Lemon', families: ['Yellow']},
  {label: 'Orange', key: 'orange', chip: 'Orange', families: ['Orange & Terracotta']},
  {label: 'Neutrals', key: 'neutrals', chip: 'Ivory', families: ['White & Ivory', 'Beige & Champagne', 'Gold', 'Silver', 'Grey']},
  {label: 'Darks', key: 'darks', chip: 'Espresso', families: ['Black', 'Navy', 'Brown']},
  {label: 'Multicolor & Custom', families: ['Multicolor & Custom']},
];
const colorsByName = new Map(data.colors.map(entry => [entry.name, entry]));
const solids = data.colors.filter(entry => entry.hex);
for (const entry of data.colors) {
  if (families.filter(group => group.families.includes(entry.family)).length !== 1 ||
      entry.name !== entry.source.label || entry.hex !== (entry.source.color || '') ||
      (entry.hex && !/^#[0-9a-f]{6}$/i.test(entry.hex)) || !/^[A-Za-z0-9 -]+$/.test(entry.name)) {
    throw new Error('Review color catalog entry: ' + entry.name);
  }
}
const popular = ['Black', 'Navy Blue', 'Dusty Rose', 'Sage Green', 'Sky Blue', 'Burgundy', 'Emerald', 'Champagne'];
const pickerLines = entries => entries.map(entry => entry.name + entry.hex).join('\n');
const picker = {popular: pickerLines(popular.map(name => colorsByName.get(name)))};
const groupLines = [];
for (const group of families) {
  const entries = data.colors.filter(entry => group.families.includes(entry.family));
  const chip = group.chip ? colorsByName.get(group.chip).hex : '#D9D9D9';
  groupLines.push([group.label, chip, entries.map(entry => entry.name).join(',')].join(':'));
  if (group.key) picker[group.key] = pickerLines(entries.filter(entry => entry.hex));
}
const colorCatalog = [
  '{%- doc -%}',
  '  Generated by scripts/build-material-guide-catalog.cjs.',
  '  @param {string} format - groups, pairs, or picker',
  '{%- enddoc -%}',
  '{%- case format -%}',
  "{%- when 'groups' -%}", ...groupLines,
  "{%- when 'pairs' -%}", solids.map(entry => entry.name.toLowerCase() + ':' + entry.hex).join(','),
  "{%- when 'picker' -%}", JSON.stringify(picker, null, 2),
  '{%- endcase -%}', '',
];
fs.writeFileSync(path.join(root, 'theme/snippets/color-catalog.liquid'), colorCatalog.join('\n'));
