// Regenerate code-only catalog snippets from the reviewed source record.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'data/material-guide-catalog.json'), 'utf8'));
const quote = value => {
  if (/["\r\n\\]/.test(value)) throw new Error('Liquid literal requires review: ' + value);
  return '"' + value + '"';
};
const slug = value => value.toLowerCase().replace(/[^a-z0-9]+/g, '-');
for (const kind of ['color', 'fabric']) {
  const items = kind === 'fabric' ? data.fabricDisplayOrder.map(name => {
    const entry = data.fabrics.find(entry => entry.name === name);
    if (!entry) throw new Error('Unknown displayed fabric: ' + name);
    return entry;
  }) : data.colors;
  const names = new Set();
  const lines = ['{% comment %}Generated by scripts/build-material-guide-catalog.cjs. Source: data/material-guide-catalog.json.{% endcomment %}'];
  for (const entry of items) {
    if (names.has(entry.name)) throw new Error('Duplicate catalog name: ' + entry.name);
    names.add(entry.name);
    const values = {entry_id: slug(entry.name), name: entry.name, description: entry.description, image_file: entry.image?.file || '', image_caption: entry.imageCaption, product_handle: entry.product};
    if (kind === 'color') Object.assign(values, {family: entry.family, hex: entry.hex});
    else Object.assign(values, {finish: entry.finish, drape: entry.drape, feel: entry.feel, notes: entry.notes, detail_position: entry.detailPosition, display_number: String(names.size).padStart(2, '0')});
    for (const [key, value] of Object.entries(values)) {
      if (typeof value !== 'string') throw new Error('Missing field: ' + entry.name + '/' + key);
    }
    const params = Object.entries(values).map(([key, value]) => key + ': ' + quote(value)).join(', ');
    lines.push(`{% render 'guide-${kind}-entry', section: section${kind === 'color' ? ', mode: mode' : ''}, ${params} %}`);
  }
  fs.writeFileSync(path.join(root, `theme/snippets/guide-${kind}-catalog.liquid`), lines.join('\n') + '\n');
  console.log(`Generated ${items.length} ${kind} entries`);
}
